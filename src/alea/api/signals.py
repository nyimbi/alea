"""The signal store and the review queue.

Layer 7's output contract is :class:`~alea.signals.models.Signal`, and the review
queue is SQLite (10-layer7 §6.1). This module owns the API's view of both: it
serves signals and records review decisions.

**A signal is stored as its validated JSON, not as ``signal.__dict__``.** The
specification dumps ``__dict__``, which bypasses pydantic on the way out, so a
row whose schema has moved since it was written reads back as an object that
never validated. Storing ``model_dump(mode="json")`` and re-validating on read
means a schema change fails loudly at the row, not silently at a caller.

**The review record is append-only.** An edit produces a new signal version and
retains the original (10-layer7 §6.2). That is what makes "the model changed
because an analyst corrected 100 MW to 1000 MW" auditable, and it is the only
way the extraction layer's accuracy -- extracted minus confirmed -- is
measurable, which is the honest basis for an auto-acceptance threshold.
"""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any

from alea._uuid7 import uuid7str
from alea.api.db import AsyncDatabase
from alea.api.views import ReviewActionOut, SignalOut, SignalReviewRequest, SignalSummaryOut
from alea.io.artefacts import utcnow
from alea.logging import get_logger
from alea.signals.models import Signal, SignalType

logger = get_logger(__name__)

SIGNAL_SCHEMA = """
CREATE TABLE IF NOT EXISTS signals (
	signal_id     TEXT PRIMARY KEY,
	signal_type   TEXT NOT NULL,
	confidence    REAL NOT NULL,
	country_iso   TEXT,
	requires_review INTEGER NOT NULL DEFAULT 1,
	version       INTEGER NOT NULL DEFAULT 1,
	supersedes    TEXT,
	payload       TEXT NOT NULL,
	extracted_at  TEXT NOT NULL,
	stored_at     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS signals_type ON signals (signal_type, signal_id);
CREATE INDEX IF NOT EXISTS signals_country ON signals (country_iso, signal_id);
CREATE INDEX IF NOT EXISTS signals_pending ON signals (requires_review, signal_id);

-- Append-only. Nothing updates a row here; a correction is a new row.
CREATE TABLE IF NOT EXISTS review_actions (
	action_id   TEXT PRIMARY KEY,
	signal_id   TEXT NOT NULL,
	analyst     TEXT NOT NULL,
	action      TEXT NOT NULL,
	edits       TEXT NOT NULL DEFAULT '{}',
	reason      TEXT NOT NULL DEFAULT '',
	at          TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS review_actions_signal ON review_actions (signal_id, at);
"""


class SignalNotFound(Exception):
	"""No signal with that id."""


class SignalStore:
	"""Serves signals and records review decisions."""

	def __init__(self, path: str, *, database: AsyncDatabase | None = None) -> None:
		assert path, "a signal store needs a path"
		self._database = database or AsyncDatabase(path, schema=SIGNAL_SCHEMA)

	@property
	def database(self) -> AsyncDatabase:
		return self._database

	async def connect(self) -> None:
		await self._database.connect()

	async def close(self) -> None:
		await self._database.close()

	# -- writes ------------------------------------------------------------

	async def add(self, signal: Signal, *, priority: float | None = None) -> SignalOut:
		"""Store a signal.

		``INSERT OR IGNORE``: a signal id is generated by the scanner, and a
		re-run that produces the same id has already stored it. Overwriting would
		discard a review decision recorded against the earlier row.
		"""
		assert isinstance(signal, Signal), f"expected a Signal, got {type(signal).__name__}"
		payload = signal.model_dump(mode="json")
		if priority is not None:
			payload["priority"] = priority
		await self._database.execute(
			"""
			INSERT OR IGNORE INTO signals
				(signal_id, signal_type, confidence, country_iso, requires_review,
				 version, payload, extracted_at, stored_at)
			VALUES (?, ?, ?, ?, ?, 1, ?, ?, ?)
			""",
			(
				signal.signal_id,
				str(signal.signal_type),
				signal.confidence,
				signal.country_iso,
				1 if signal.requires_review else 0,
				json.dumps(payload, sort_keys=True),
				signal.extracted_at.isoformat(),
				utcnow().isoformat(),
			),
		)
		return SignalOut.from_signal(signal)

	async def add_many(self, signals: list[Signal]) -> int:
		"""Store many signals in one transaction."""
		assert signals is not None, "add_many needs a list"
		rows = [
			(
				signal.signal_id,
				str(signal.signal_type),
				signal.confidence,
				signal.country_iso,
				1 if signal.requires_review else 0,
				json.dumps(signal.model_dump(mode="json"), sort_keys=True),
				signal.extracted_at.isoformat(),
				utcnow().isoformat(),
			)
			for signal in signals
		]
		return await self._database.executemany(
			"""
			INSERT OR IGNORE INTO signals
				(signal_id, signal_type, confidence, country_iso, requires_review,
				 version, payload, extracted_at, stored_at)
			VALUES (?, ?, ?, ?, ?, 1, ?, ?, ?)
			""",
			rows,
		)

	async def review(self, signal_id: str, request: SignalReviewRequest) -> ReviewActionOut:
		"""Record a review decision and apply its consequence to the signal.

		Confirm and reject clear ``requires_review`` on the *current* version, so
		the integration stage (which refuses an unreviewed signal) will accept it.
		An edit writes a *new* row carrying the edits and a higher version, and
		leaves the original in place.
		"""
		assert signal_id, "review needs a signal id"
		assert request is not None, "review needs a decision"
		row = await self._database.fetchone(
			"SELECT payload, version FROM signals WHERE signal_id = ?", (signal_id,)
		)
		if row is None:
			raise SignalNotFound(f"no signal {signal_id}")

		now = utcnow()
		action_id = uuid7str()
		await self._database.execute(
			"""
			INSERT INTO review_actions (action_id, signal_id, analyst, action, edits, reason, at)
			VALUES (?, ?, ?, ?, ?, ?, ?)
			""",
			(
				action_id,
				signal_id,
				request.analyst,
				request.action,
				json.dumps(request.edits, sort_keys=True),
				request.reason,
				now.isoformat(),
			),
		)

		if request.action == "edit":
			await self._apply_edit(signal_id, request, version=int(row["version"]) + 1, at=now)
		else:
			# confirm / reject / merge all resolve the review requirement. The
			# decision itself is in the append-only action table; the signal row
			# carries only whether it still needs a human.
			await self._database.execute(
				"UPDATE signals SET requires_review = 0 WHERE signal_id = ?", (signal_id,)
			)

		logger.info(
			"signals.reviewed",
			signal_id=signal_id,
			action=request.action,
			analyst=request.analyst,
		)
		return ReviewActionOut(
			action_id=action_id,
			signal_id=signal_id,
			analyst=request.analyst,
			action=request.action,
			edits=request.edits,
			reason=request.reason,
			at=now,
		)

	async def _apply_edit(
		self, signal_id: str, request: SignalReviewRequest, *, version: int, at: datetime
	) -> None:
		"""Write an edited signal as a new version, validating the result.

		The edited signal is validated against the ``Signal`` contract before it
		is stored: an edit that produces an invalid signal must fail here, where
		an analyst can see it, not at the integration stage hours later.
		"""
		assert version >= 2, "an edit produces version 2 or later"
		row = await self._database.fetchone(
			"SELECT payload, signal_id FROM signals WHERE signal_id = ?", (signal_id,)
		)
		if row is None:  # pragma: no cover - checked by the caller
			raise SignalNotFound(f"no signal {signal_id}")
		payload = json.loads(row["payload"])
		payload.update(request.edits)
		# requires_review is cleared on the edited version: the edit *is* the
		# review. Re-validating is what makes the correction a checked fact.
		payload["requires_review"] = False
		edited = Signal.model_validate(payload)
		new_id = edited.signal_id
		if new_id == signal_id:
			# The analyst did not supply a new id, so derive one that keeps the
			# lineage visible and stays a valid UUID-shaped string.
			new_id = f"{signal_id}.v{version}"

		await self._database.execute(
			"""
			INSERT INTO signals
				(signal_id, signal_type, confidence, country_iso, requires_review,
				 version, supersedes, payload, extracted_at, stored_at)
			VALUES (?, ?, ?, ?, 0, ?, ?, ?, ?, ?)
			""",
			(
				new_id,
				str(edited.signal_type),
				edited.confidence,
				edited.country_iso,
				version,
				signal_id,
				json.dumps(edited.model_dump(mode="json"), sort_keys=True),
				edited.extracted_at.isoformat(),
				at.isoformat(),
			),
		)
		await self._database.execute(
			"UPDATE signals SET requires_review = 0 WHERE signal_id = ?", (signal_id,)
		)

	# -- reads -------------------------------------------------------------

	async def get(self, signal_id: str) -> SignalOut | None:
		"""One signal, or ``None``."""
		assert signal_id, "get needs a signal id"
		row = await self._database.fetchone(
			"SELECT payload FROM signals WHERE signal_id = ?", (signal_id,)
		)
		if row is None:
			return None
		return SignalOut.model_validate(json.loads(row["payload"]))

	async def require(self, signal_id: str) -> SignalOut:
		signal = await self.get(signal_id)
		if signal is None:
			raise SignalNotFound(f"no signal {signal_id}")
		return signal

	async def list(
		self,
		*,
		signal_type: SignalType | None = None,
		country: str | None = None,
		requires_review: bool | None = None,
		since: datetime | None = None,
		limit: int = 100,
		offset: int = 0,
	) -> tuple[list[SignalSummaryOut], int]:
		"""A page of signals and the total matching the same filters."""
		assert limit > 0 and offset >= 0, "limit must be positive and offset non-negative"
		clauses: list[str] = []
		params: list[Any] = []
		if signal_type is not None:
			clauses.append("signal_type = ?")
			params.append(str(signal_type))
		if country is not None:
			clauses.append("country_iso = ?")
			params.append(country.upper())
		if requires_review is not None:
			clauses.append("requires_review = ?")
			params.append(1 if requires_review else 0)
		if since is not None:
			clauses.append("extracted_at >= ?")
			params.append(since.isoformat())

		where = f" WHERE {' AND '.join(clauses)}" if clauses else ""
		total_row = await self._database.fetchone(
			f"SELECT COUNT(*) AS n FROM signals{where}", tuple(params)
		)
		total = int(total_row["n"]) if total_row is not None else 0

		rows = await self._database.fetchall(
			f"SELECT payload, requires_review FROM signals{where} "
			f"ORDER BY extracted_at DESC, signal_id DESC LIMIT ? OFFSET ?",
			(*params, limit, offset),
		)
		items = [_summary(json.loads(row["payload"]), bool(row["requires_review"])) for row in rows]
		return items, total

	async def actions(self, signal_id: str) -> list[ReviewActionOut]:
		"""The append-only review history of one signal, oldest first."""
		assert signal_id, "actions needs a signal id"
		rows = await self._database.fetchall(
			"SELECT * FROM review_actions WHERE signal_id = ? ORDER BY at ASC, action_id ASC",
			(signal_id,),
		)
		return [
			ReviewActionOut(
				action_id=row["action_id"],
				signal_id=row["signal_id"],
				analyst=row["analyst"],
				action=row["action"],
				edits=json.loads(row["edits"]),
				reason=row["reason"],
				at=datetime.fromisoformat(row["at"]),
			)
			for row in rows
		]

	async def pending_count(self) -> int:
		"""How many signals still await a human. Read by the health endpoint."""
		row = await self._database.fetchone(
			"SELECT COUNT(*) AS n FROM signals WHERE requires_review = 1"
		)
		return int(row["n"]) if row is not None else 0


def _summary(payload: dict[str, Any], requires_review: bool) -> SignalSummaryOut:
	"""Project a stored payload onto the listing model.

	``requires_review`` comes from the row rather than the payload: the row is
	what a review decision updates, and the payload is the immutable extraction.
	"""
	assert isinstance(payload, dict), "a stored signal payload is an object"
	return SignalSummaryOut(
		signal_id=payload["signal_id"],
		signal_type=payload["signal_type"],
		confidence=payload["confidence"],
		country_iso=payload.get("country_iso"),
		source_name=payload.get("source_name", ""),
		source_url=payload.get("source_url", ""),
		extracted_at=datetime.fromisoformat(payload["extracted_at"]),
		requires_review=requires_review,
	)


__all__ = ["SIGNAL_SCHEMA", "SignalNotFound", "SignalStore"]
