"""Regenerate docs/param_coupling_worklist.md from the loaded graph.

Run: uv run python scripts/gen_coupling_worklist.py
The document is a register of load_graph().uncoupled(); never hand-edit it.
"""
from __future__ import annotations

import re
from pathlib import Path

from alea.prg.graph import load_graph

OUT = Path(__file__).resolve().parent.parent / "docs" / "param_coupling_worklist.md"
CATEGORICAL = {"categorical", "Type.CATEGORICAL", "string", "bool", "boolean"}


def _first_sentence(text: str, limit: int = 170) -> str:
	text = " ".join(text.split())
	cut = text.find(". ")
	text = text if cut < 0 else text[: cut + 1]
	text = text if len(text) <= limit else text[: limit - 1].rstrip() + "…"
	return text.replace("|", "/")


SURVEY = Path(__file__).resolve().parent.parent / "docs" / "research" / "placeholder-survey.md"


def _survey_reasons() -> dict[str, str]:
	"""Per-node reason a placeholder stayed open, from the survey's `- `node` — reason` bullets."""
	reasons: dict[str, str] = {}
	for line in SURVEY.read_text().splitlines():
		hit = re.match(r"^- `([a-z0-9_]+)` — (.+)$", line)
		if hit:
			reasons.setdefault(hit.group(1), _first_sentence(hit.group(2), 230))
	for name in ("scenario_description", "scenario_owner", "scenario_tag", "parameter_overrides"):
		# The survey's NAME-blocked four are described in prose, not bullets.
		reasons.setdefault(name, "Free text or a mapping; `ParameterType` has no text or mapping type, so it is recorded and left.")
	return reasons


def main() -> None:
	graph = load_graph()
	reasons = _survey_reasons()
	rows: dict[str, list[tuple[str, str, str, str, str]]] = {
		"tombstone": [], "categorical": [], "non-scalar": [], "numeric": [],
	}
	for name in graph.uncoupled():
		node = graph.node(name)
		desc = node.description or ""
		if node.deprecated_by is not None or node.status == "deprecated" or desc.startswith(("DEPRECATED", "Retired")):
			cls = "tombstone"
		elif str(node.type) in CATEGORICAL:
			cls = "categorical"
		elif node.unit in (None, "None") and node.default == 500000.0:
			cls = "non-scalar"
		else:
			cls = "numeric"
		rows[cls].append((name, str(node.unit), str(node.default), _first_sentence(desc), reasons.get(name, "")))
	total = sum(len(v) for v in rows.values())
	assert total == len(graph.uncoupled()), (total, len(graph.uncoupled()))
	meaning = {
		"numeric": "Typed, with a real unit and value. Coupling needs a base node or a physical identity the graph does not hold yet.",
		"non-scalar": "Registers, record sets, procedures and free text that the catalog shipped as `float` with the 500000 stub. None is a quantity, and `ParameterType` has no text or mapping type, so each is recorded and left (decision, batch 87); retyping would assert a number that does not exist.",
		"categorical": "A level name. A level has no arithmetic, so it can never be an equation operand; it belongs in a register.",
		"tombstone": "Retired id. Coupled only as the determined side of a forwarding equality.",
	}
	lines = [
		"# Coupling worklist", "",
		f"Generated by `scripts/gen_coupling_worklist.py` from `load_graph().uncoupled()`. {total} nodes; do not hand-edit.", "",
		"| Class | Count |", "|---|---|",
	]
	lines += [f"| {c} | {len(rows[c])} |" for c in rows]
	for cls, items in rows.items():
		lines += ["", f"## {cls.capitalize()} ({len(items)})", "", meaning[cls], "",
			"| Node | Unit | Default | Meaning | Why open (placeholder survey) |", "|---|---|---|---|---|"]
		lines += [f"| `{n}` | {u} | {d} | {t} | {r.replace('|', '/')} |" for n, u, d, t, r in items]
	OUT.write_text("\n".join(lines) + "\n")
	print({c: len(v) for c, v in rows.items()})


if __name__ == "__main__":
	main()
